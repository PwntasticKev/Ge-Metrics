#!/usr/bin/env node
// Regenerates src/domain/flipping/data/taxExempt.js: items the Grand Exchange
// doesn't charge its 2% fee on, from the "Exempt from tax" list on the wiki's
// Grand Exchange page.
//
//   node scripts/generate-tax-exempt.js

import { writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const USER_AGENT = 'GE-Metrics tax exemption generator (https://ge-metrics.com)'
const PAGE_URL = 'https://oldschool.runescape.wiki/api.php?action=parse&page=Grand_Exchange&prop=wikitext&format=json'
const MAPPING_URL = 'https://prices.runescape.wiki/api/v1/osrs/mapping'
const MIN_EXPECTED = 20
const OUTPUT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../src/domain/flipping/data/taxExempt.js')

async function getJson (url) {
  const response = await fetch(url, { headers: { 'User-Agent': USER_AGENT } })
  if (!response.ok) throw new Error(`${url} returned ${response.status}`)
  return response.json()
}

// Links in the "Exempt from tax" section. "[[Page|Shown name]]": the shown
// name is usually the exact item (e.g. "Games necklace(8)"), the page name is
// the fallback (e.g. "Old school bond" from "[[Old school bond]]s").
export function parseExemptLinks (wikitext) {
  const start = wikitext.indexOf('===Exempt from tax===')
  if (start < 0) throw new Error('No "Exempt from tax" section on the Grand Exchange page')
  const end = wikitext.indexOf('\n==', start + 5)
  const section = wikitext.slice(start, end < 0 ? undefined : end)
  return [...section.matchAll(/\[\[([^\]|]+)(?:\|([^\]]+))?\]\]/g)].map(([, page, shown]) => ({ page: page.trim(), shown: shown?.trim() ?? null }))
}

async function main () {
  const [page, mapping] = await Promise.all([getJson(PAGE_URL), getJson(MAPPING_URL)])
  const byName = new Map(mapping.map(item => [item.name.toLowerCase(), item]))
  const links = parseExemptLinks(page.parse.wikitext['*'])
  const unresolved = []
  const items = new Map()
  for (const { page: target, shown } of links) {
    const item = (shown && byName.get(shown.toLowerCase())) || byName.get(target.toLowerCase())
    if (item) items.set(item.id, item.name)
    else unresolved.push(shown ?? target)
  }
  if (items.size < MIN_EXPECTED) throw new Error(`Only ${items.size} exempt items resolved; not overwriting.`)
  const sorted = [...items].sort((a, b) => a[1].localeCompare(b[1]))
  const header = '// Generated by scripts/generate-tax-exempt.js from the OSRS Wiki Grand Exchange page. Do not edit.\n'
  const body = sorted.map(([id, name]) => `  ${id}, // ${name}`).join('\n')
  await writeFile(OUTPUT, `${header}export default [\n${body}\n]\n`)
  console.log(`Wrote ${items.size} tax-exempt items to ${path.relative(process.cwd(), OUTPUT)}`)
  if (unresolved.length) console.warn('Unresolved (not GE items or renamed):', unresolved)
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  main().catch(error => {
    console.error(error)
    process.exit(1)
  })
}
