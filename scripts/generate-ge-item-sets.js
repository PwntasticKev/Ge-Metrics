#!/usr/bin/env node
// Regenerates src/domain/flipping/data/geItemSets.js from the OSRS Wiki.
//
// Source: the "Item set" wiki page, which lists every Grand Exchange item set
// and the components it exchanges for. Names are resolved to item ids with the
// prices API mapping. Run after game updates add new sets:
//
//   node scripts/generate-ge-item-sets.js

import { writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const USER_AGENT = 'GE-Metrics item set generator (https://ge-metrics.com)'
const WIKI_PAGE_URL = 'https://oldschool.runescape.wiki/api.php?action=parse&page=Item_set&prop=wikitext&format=json'
const MAPPING_URL = 'https://prices.runescape.wiki/api/v1/osrs/mapping'
// Refuse to overwrite the committed list if parsing suddenly finds far fewer sets.
const MIN_EXPECTED_SETS = 100
const OUTPUT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../src/domain/flipping/data/geItemSets.js')

async function getJson (url) {
  const response = await fetch(url, { headers: { 'User-Agent': USER_AGENT } })
  if (!response.ok) throw new Error(`${url} returned ${response.status}`)
  return response.json()
}

// Each table row looks like:
// |{{plinkt|Dharok's armour set}} ... {{#expr:{{GEP|Dharok's helm}}+{{GEP|Dharok's platebody}}+...}}
export function parseItemSetRows (wikitext) {
  return wikitext.split('|-').flatMap(row => {
    const setMatch = row.match(/\{\{plinkt\|([^}|]+)/)
    // Only the "pieces" cell: the expression runs to the end of its line.
    const exprMatch = row.match(/#expr:([^\n]*)/)
    if (!setMatch || !exprMatch) return []
    const cell = exprMatch[1]
    const parts = [...cell.matchAll(/\{\{GEP\|([^}|]+)\}\}\s*(?:\*\s*(\d+))?/g)]
      .map(([, name, qty]) => ({ name: name.trim(), qty: Number(qty || 1) }))
    // A GEP we couldn't read would silently drop a part and fake a profit.
    const gepCount = (cell.match(/\{\{GEP\|/g) ?? []).length
    if (gepCount !== parts.length) {
      throw new Error(`Unparsed part in "${setMatch[1].trim()}": found ${gepCount} GEP calls, parsed ${parts.length}`)
    }
    return parts.length ? [{ name: setMatch[1].trim(), parts }] : []
  })
}

async function main () {
  const [page, mapping] = await Promise.all([getJson(WIKI_PAGE_URL), getJson(MAPPING_URL)])
  const nameCounts = mapping.reduce((acc, item) => {
    const key = item.name.toLowerCase()
    return acc.set(key, (acc.get(key) ?? 0) + 1)
  }, new Map())
  // Names shared by several items can't be resolved safely; leave them unresolved.
  const idByName = new Map(mapping.filter(item => nameCounts.get(item.name.toLowerCase()) === 1).map(item => [item.name.toLowerCase(), item.id]))
  const rows = parseItemSetRows(page.parse.wikitext['*'])

  const unresolved = []
  const bySetId = new Map()
  for (const row of rows) {
    const setId = idByName.get(row.name.toLowerCase())
    const parts = row.parts.map(p => ({ id: idByName.get(p.name.toLowerCase()), qty: p.qty, name: p.name }))
    if (!setId || parts.some(p => !p.id)) {
      unresolved.push(row.name)
      continue
    }
    bySetId.set(setId, { setId, name: row.name, parts: parts.map(({ id, qty }) => ({ id, qty })) })
  }

  const sets = [...bySetId.values()].sort((a, b) => a.name.localeCompare(b.name))
  if (sets.length < MIN_EXPECTED_SETS) {
    throw new Error(`Only ${sets.length} sets parsed (expected at least ${MIN_EXPECTED_SETS}); the wiki page format may have changed. Not overwriting.`)
  }
  // A JS module (not .json) so Vite, Node and Metro can all import it without import attributes.
  const header = '// Generated by scripts/generate-ge-item-sets.js from the OSRS Wiki "Item set" page. Do not edit.\n'
  await writeFile(OUTPUT, `${header}export default ${JSON.stringify(sets, null, 2)}\n`)
  console.log(`Wrote ${sets.length} sets to ${path.relative(process.cwd(), OUTPUT)}`)
  if (unresolved.length) console.warn(`Skipped ${unresolved.length} unresolved sets:`, unresolved)
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  main().catch(error => {
    console.error(error)
    process.exit(1)
  })
}
